"""GEO checks: AI crawler access, llms.txt, citation-friendliness and entity signals."""

from __future__ import annotations

import re
from collections.abc import Iterator
from itertools import combinations

from ranq import sources
from ranq.analysis import pagetype as pt
from ranq.checks.base import AuditContext, check
from ranq.geo.analysis import GeoReport
from ranq.models import Category, Effort, Issue, Severity

G = Category.GEO
AI_BOTS_DOC = "https://platform.openai.com/docs/bots"


def _geo(ctx: AuditContext) -> GeoReport | None:
    return ctx.extras.get("geo")


@check("ai-crawler-access", G)
def ai_crawler_access(ctx: AuditContext) -> Iterator[Issue]:
    geo = _geo(ctx)
    if geo is None or ctx.crawl.robots.unreachable:
        return
    if geo.policy_explicit and geo.mismatches:
        yield Issue(
            "ai-policy-mismatch",
            f"Live robots.txt differs from your AI crawler policy for {len(geo.mismatches)} bot(s)",
            Severity.MEDIUM,
            G,
            "ranq.yaml declares a policy for these bots, but the live robots.txt does something else.",
            "Deploy the robots.txt generated by `ranq fix` (review the diff first).",
            urls=[f"{ctx.site}/robots.txt"],
            evidence=geo.mismatches,
            source=sources.ROBOTS_TXT,
        )
    blocked = {
        b.token: b.operator for b in geo.bots if b.purpose in ("search", "user") and not b.allowed
    }
    if blocked and not geo.policy_explicit:
        yield Issue(
            "ai-search-bots-blocked",
            f"{len(blocked)} AI search/assistant crawler(s) are blocked",
            Severity.MEDIUM,
            G,
            "These bots fetch pages so AI answers can cite and link them. Blocking them removes "
            "your pages from those answers. If that is intentional, set the policy in ranq.yaml "
            "and this finding becomes a policy check instead.",
            "Allow search/user-fetch bots (preset 'search-only' keeps training crawlers blocked).",
            urls=[f"{ctx.site}/robots.txt"],
            evidence=blocked,
            source=AI_BOTS_DOC,
        )
    if not any(b.explicit for b in geo.bots):
        yield Issue(
            "ai-policy-implicit",
            "Optional: define an explicit AI crawler policy",
            Severity.INFO,
            G,
            "Your robots.txt currently lets AI crawlers follow the normal '*' rules. That is valid "
            "and needs no change when the public site has nothing you want to restrict. Explicit "
            "AI rules are mainly useful when you want different policies for training, search or "
            "user-initiated bots.",
            "Leave it as-is, or add explicit rules only if the site has paths you intentionally "
            "want crawlers to avoid (for example staging, admin/internal areas, duplicate utility "
            "pages or crawl-heavy endpoints), or if you want a specific AI-bot policy.",
            urls=[f"{ctx.site}/robots.txt"],
            evidence={b.token: "allowed" if b.allowed else "blocked" for b in geo.bots},
            source=sources.ROBOTS_TXT,
        )


@check("llms-txt", G)
def llms_txt(ctx: AuditContext) -> Iterator[Issue]:
    geo = _geo(ctx)
    if geo is None:
        return
    if geo.llms_txt_status != 200:
        yield Issue(
            "llms-txt-missing",
            "Optional: no /llms.txt file",
            Severity.INFO,
            G,
            "llms.txt is a proposed convention for giving AI tools a curated Markdown map of a "
            "site. It is not required for SEO, indexing or AI visibility, and major AI providers "
            "do not require it.",
            "No action is required. Publish llms.txt only if you want to provide an additional "
            "machine-readable site guide for agents and tools that choose to read it.",
            urls=[f"{ctx.site}/llms.txt"],
            evidence={"status": geo.llms_txt_status},
            source=sources.LLMS_TXT,
        )


@check("citation-friendliness", G)
def citation_friendliness(ctx: AuditContext) -> Iterator[Issue]:
    geo = _geo(ctx)
    if geo is None or not geo.citation:
        return
    low = {c.url: c.score for c in geo.citation if c.score < 40}
    if low:
        weakest = {c.url: c.components for c in geo.citation if c.url in low}
        yield Issue(
            "low-citation-friendliness",
            f"{len(low)} page(s) score below 40/100 for citation-friendliness",
            Severity.MEDIUM,
            G,
            "Heuristic: these pages have few quotable factual statements, unsourced numbers, no "
            "date or author, little structure, or content hidden behind JavaScript - all of which "
            "make it harder for AI answer engines to retrieve, quote and attribute them.",
            "Add a clear definition and specific facts, link sources for statistics, show author "
            "and updated date, use question headings with direct answers, and server-render text.",
            effort=Effort.MEDIUM,
            urls=sorted(low, key=lambda u: low[u]),
            evidence=weakest,
            source=sources.HELPFUL_CONTENT,
            estimate=True,
        )


@check("entity-signals", G)
def entity_signals(ctx: AuditContext) -> Iterator[Issue]:
    geo = _geo(ctx)
    if geo is None or geo.entity is None:
        return
    ent = geo.entity
    if not ent.same_as:
        yield Issue(
            "entity-no-sameas",
            "Optional: no sameAs profile links for your brand entity",
            Severity.INFO,
            G,
            "sameAs links can help search engines and AI systems connect your site to official "
            "profiles on other platforms, but they are not required for a valid Organization "
            "entity or for normal indexing.",
            "No action is required. Add only official, relevant profiles when they exist; do not "
            "create profiles just to satisfy this check.",
            urls=[ctx.crawl.start_url],
            source=f"{sources.G}/appearance/structured-data/organization",
        )
    if len(ent.name_variants) > 1:
        yield Issue(
            "brand-name-inconsistent",
            f"Brand name appears in {len(ent.name_variants)} variants",
            Severity.LOW,
            G,
            "og:site_name, structured data and title suffixes use different spellings of your name. "
            "Consistent naming strengthens entity recognition.",
            "Use one exact brand name everywhere (site, markup, profiles, directories).",
            evidence=ent.name_variants,
            urls=[ctx.crawl.start_url],
            estimate=True,
            source=f"{sources.G}/appearance/site-names",
        )
    if ent.missing_facts:
        yield Issue(
            "entity-facts-missing",
            "Entity facts are incomplete",
            Severity.INFO,
            G,
            "These basic facts are not set in ranq.yaml or found in your markup, so the "
            "generated fact sheet and Organization markup leave them out.",
            "Fill in the entity section of ranq.yaml only for facts that are accurate and useful; "
            "missing optional facts do not require filler values.",
            evidence={"missing": ent.missing_facts},
            urls=[ctx.crawl.start_url],
            source=sources.SD_GENERAL,
        )


STOPWORDS = frozenset(
    [
        "the",
        "and",
        "for",
        "with",
        "that",
        "this",
        "from",
        "your",
        "our",
        "are",
        "was",
        "were",
        "have",
        "has",
        "into",
        "their",
        "they",
        "them",
        "who",
        "what",
        "which",
        "while",
        "where",
        "when",
        "about",
        "based",
        "also",
        "more",
        "most",
        "very",
        "just",
        "than",
        "then",
    ]
)
WORD_RE = re.compile(r"[a-z0-9]+")


def _terms(text: str, brand: str | None) -> set[str]:
    words = WORD_RE.findall(text.lower())
    skip = set(WORD_RE.findall((brand or "").lower())) | STOPWORDS
    return {w.rstrip("s") for w in words if len(w) >= 3 and w not in skip}


def _llms_summary(live: str | None) -> str | None:
    for line in (live or "").splitlines():
        if line.startswith(">"):
            return line.lstrip("> ").strip() or None
    return None


def brand_descriptions(ctx: AuditContext, geo: GeoReport | None) -> dict[str, str]:
    """The places that state who the brand is, which AI systems read and should agree."""
    found: dict[str, str] = {}
    if ctx.config.entity.description:
        found["ranq.yaml entity.description"] = ctx.config.entity.description
    home = ctx.crawl.pages.get(ctx.crawl.start_url)
    for node in pt.top_nodes(home) if home else []:
        if pt.node_types(node) & {"Organization", "LocalBusiness", "Corporation"}:
            if isinstance(node.get("description"), str):
                found["JSON-LD Organization.description"] = node["description"]
            break
    summary = _llms_summary(geo.llms_txt_live if geo else None)
    if summary:
        found["llms.txt summary"] = summary
    return found


@check("brand-consistency", G)
def brand_consistency(ctx: AuditContext) -> Iterator[Issue]:
    geo = _geo(ctx)
    found = brand_descriptions(ctx, geo)
    brand = ctx.config.entity.name or (geo.entity.name if geo and geo.entity else None)
    terms = {k: _terms(v, brand) for k, v in found.items()}
    pairs = []
    for a, b in combinations(terms, 2):
        union = terms[a] | terms[b]
        if union:
            pairs.append(len(terms[a] & terms[b]) / len(union))
    if pairs and min(pairs) < 0.3:
        yield Issue(
            "brand-description-inconsistent",
            "Review wording differences between brand descriptions",
            Severity.INFO,
            G,
            "These descriptions have low word overlap. This heuristic cannot distinguish "
            "a contradiction from compatible paraphrases and does not affect the health score.",
            "Review the descriptions for factual conflicts. Keep accurate paraphrases; "
            "identical wording across markup, llms.txt and config is not required.",
            effort=Effort.LOW,
            urls=[ctx.crawl.start_url],
            evidence=found,
            estimate=True,
            source=sources.HELPFUL_CONTENT,
        )


@check("contact-visibility", G)
def contact_visibility(ctx: AuditContext) -> Iterator[Issue]:
    hidden = sorted(p.url for p in ctx.pages if "/cdn-cgi/l/email-protection" in p.html)
    if hidden:
        yield Issue(
            "email-obfuscated",
            "Contact email is hidden by Cloudflare Email Obfuscation",
            Severity.LOW,
            G,
            "Cloudflare replaces email addresses with a /cdn-cgi/l/email-protection link that "
            "only JavaScript can decode, so crawlers and AI assistants cannot read how to "
            "contact you (a trust and entity signal).",
            "Turn off Scrape Shield -> Email Address Obfuscation, or wrap the address on your "
            "contact page in <!--email_off-->...<!--/email_off--> so it stays readable there.",
            effort=Effort.LOW,
            urls=hidden,
            source="https://developers.cloudflare.com/waf/tools/scrape-shield/email-address-obfuscation/",
        )
